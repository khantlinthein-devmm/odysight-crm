package thaibaht

import "testing"

func TestText(t *testing.T) {
	cases := map[float64]string{
		0:         "ศูนย์บาทถ้วน",
		1:         "หนึ่งบาทถ้วน",
		11:        "สิบเอ็ดบาทถ้วน",
		21:        "ยี่สิบเอ็ดบาทถ้วน",
		101:       "หนึ่งร้อยเอ็ดบาทถ้วน",
		1070:      "หนึ่งพันเจ็ดสิบบาทถ้วน",
		2675.50:   "สองพันหกร้อยเจ็ดสิบห้าบาทห้าสิบสตางค์",
		0.25:      "ยี่สิบห้าสตางค์",
		1000000:   "หนึ่งล้านบาทถ้วน",
		1000001:   "หนึ่งล้านหนึ่งบาทถ้วน",
		21000000:  "ยี่สิบเอ็ดล้านบาทถ้วน",
		123456.78: "หนึ่งแสนสองหมื่นสามพันสี่ร้อยห้าสิบหกบาทเจ็ดสิบแปดสตางค์",
		10:        "สิบบาทถ้วน",
		20000.01:  "สองหมื่นบาทหนึ่งสตางค์",
	}
	for in, want := range cases {
		if got := Text(in); got != want {
			t.Errorf("Text(%v) = %s, want %s", in, got, want)
		}
	}
}
